def build_cmap(tt: TTFont):
    cmap = {}
    try: cmap.update(tt.getBestCmap())
    except: pass
    for table in tt["cmap"].tables:
        if table.isUnicode():
            for cp, val in table.cmap.items():
                if isinstance(val, int):
                    try: val = tt.getGlyphName(val)
                    except: continue
                cmap[cp] = val
    return cmap

def char_to_glyph(tt: TTFont, ch: str, cmap: dict):
    cp = ord(ch)
    if cp in cmap: return cmap[cp]
    d = unicodedata.normalize("NFD", ch)
    if d and ord(d[0]) in cmap: return cmap[ord(d[0])]
    return None

def glyph_path_d(tt: TTFont, glyph_name: str):
    gs = tt.getGlyphSet()
    if glyph_name not in gs: return None
    pen = SVGPathPen(gs)
    gs[glyph_name].draw(pen)
    return pen.getCommands()

def glyph_bounds(tt: TTFont, glyph_name: str):
    gs = tt.getGlyphSet()
    pen = BoundsPen(gs)
    gs[glyph_name].draw(pen)
    return pen.bounds or (0,0,0,0)  # (xmin, ymin, xmax, ymax)

def safe_filename(ch: str):
    return ch if (ch and ch.isprintable() and ch not in r'\/:*?"<>| ') else f"u{ord(ch):04X}"

def common_transform(tt: TTFont, glyph_name: str, viewbox_em=1000, padding_pct=6.0):
    xmin,ymin,xmax,ymax = glyph_bounds(tt, glyph_name)
    gw = max(1, xmax-xmin); gh = max(1, ymax-ymin)
    pad = viewbox_em * (padding_pct/100.0)
    vb_w = viewbox_em + 2*pad; vb_h = viewbox_em + 2*pad
    scale = viewbox_em / max(gw, gh)   # échelle UNIFORME
    tx = pad + (viewbox_em - gw*scale)/2 - xmin*scale
    ty = pad + (viewbox_em - gh*scale)/2 + ymax*scale  # flip Y ensuite
    return vb_w, vb_h, scale, tx, ty

def write_svg_filled(d_path: str, tt: TTFont, glyph_name: str, out_path: str,
                     viewbox_em: int = 1000, padding_pct: float = 6.0,
                     fill_color: str = "#000", inflate_px: int = 0):
    """
    SVG rempli. Option 'inflate_px' ajoute un stroke noir autour du fill pour
    épaissir légèrement la forme (utile si tu veux des scores plus indulgents).
    """
    vb_w, vb_h, scale, tx, ty = common_transform(tt, glyph_name, viewbox_em, padding_pct)
    stroke_part = f' stroke="{fill_color}" stroke-width="{inflate_px}" stroke-linejoin="round" stroke-linecap="round"' if inflate_px>0 else ""
    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<svg width="{int(vb_w)}" height="{int(vb_h)}" viewBox="0 0 {vb_w} {vb_h}" xmlns="http://www.w3.org/2000/svg">
  <rect x="0" y="0" width="{vb_w}" height="{vb_h}" fill="white"/>
  <g transform="translate({tx:.3f},{ty:.3f}) scale({scale:.5f},{-scale:.5f})">
    <path d="{d_path}" fill="{fill_color}"{stroke_part}/>
  </g>
</svg>'''
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f: f.write(svg)

def export_filled(font_path: str, list_path: str, outdir: str,
                  size_em: int = 1000, padding_pct: float = 6.0, inflate_px: int = 0):
    tt = TTFont(font_path)
    cmap = build_cmap(tt)
    with open(list_path, "r", encoding="utf-8") as f:
        chars = [ln.strip() for ln in f if ln.strip()]
    ok = miss = 0
    for ch in chars:
        gname = char_to_glyph(tt, ch, cmap)
        if not gname: print(f"[!] Manquant: {repr(ch)} U+{ord(ch):04X}"); miss+=1; continue
        d = glyph_path_d(tt, gname)
        if not d: print(f"[!] Vide: {repr(ch)} -> {gname}"); miss+=1; continue
        out_path = os.path.join(outdir, f"{safe_filename(ch)}.svg")
        write_svg_filled(d, tt, gname, out_path, viewbox_em=size_em, padding_pct=padding_pct, inflate_px=inflate_px)
        ok+=1; print(f"[OK] {ch} -> {out_path}")
    print(f"\nTerminé: {ok} SVG remplis générés, {miss} manquants.")

